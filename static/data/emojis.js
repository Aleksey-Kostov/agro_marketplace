/* =========================================================
   ALL EMOJIS
========================================================= */

const CHAT_EMOJIS = [];


Object.values(CHAT_EMOJI_CATEGORIES).forEach(
    category => {

        category.emojis.forEach(
            character => {

                CHAT_EMOJIS.push({
                    character: character,
                    category: category.id
                });

            }
        );

    }
);


/* =========================================================
   FIND EMOJI
========================================================= */

function getChatEmojiByCharacter(character) {

    return CHAT_EMOJIS.find(
        emoji => emoji.character === character
    ) || null;
}


/* =========================================================
   RECENT EMOJIS
========================================================= */

const CHAT_RECENT_EMOJIS_KEY =
    "chat_recent_emojis";


function getRecentChatEmojis() {

    try {

        const stored =
            localStorage.getItem(
                CHAT_RECENT_EMOJIS_KEY
            );

        if (!stored) {
            return [];
        }

        const parsed =
            JSON.parse(stored);

        if (!Array.isArray(parsed)) {
            return [];
        }

        return parsed;

    } catch (error) {

        return [];

    }
}


function addRecentChatEmoji(character) {

    if (!character) {
        return;
    }

    let recent =
        getRecentChatEmojis();

    recent =
        recent.filter(
            emoji => emoji !== character
        );

    recent.unshift(character);

    recent =
        recent.slice(0, 30);

    try {

        localStorage.setItem(
            CHAT_RECENT_EMOJIS_KEY,
            JSON.stringify(recent)
        );

    } catch (error) {
        /* Ignore localStorage errors. */
    }
}
